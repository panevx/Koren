/**
 * Generates src/map/balkans.ts — the wide base map for the timeline screen:
 * coastline of the Balkans, today's Bulgaria and the Danube.
 *
 * Source: Natural Earth (public domain) via `world-atlas`: land 1:50m, countries 1:10m.
 * The Danube outside today's Bulgarian–Romanian border is a hand-placed schematic line.
 * Historical borders are NOT here — they are schematic polygons in content/timeline/epochs.json.
 *
 *   mkdir /tmp/geo && cd /tmp/geo && npm i world-atlas@2 topojson-client@3
 *   node scripts/build-balkans.mjs /tmp/geo
 */
import { createRequire } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const dir = process.argv[2]
if (!dir) throw new Error('usage: node scripts/build-balkans.mjs <folder with world-atlas and topojson-client>')
const require = createRequire(join(resolve(dir), 'package.json'))
const topojson = require('topojson-client')
const load = (f) => JSON.parse(readFileSync(require.resolve(`world-atlas/${f}`), 'utf8'))
const land50 = load('land-50m.json')
const world10 = load('countries-10m.json')

// Must match src/map/wide.ts
const LON0 = 18.3, LON1 = 30.8, LAT0 = 39.3, LAT1 = 47.3, PHI = 43.3
const COS = Math.cos((PHI * Math.PI) / 180)
const W = 1000
const K = W / ((LON1 - LON0) * COS)
const H = Math.round((LAT1 - LAT0) * K)
const project = ([lon, lat]) => [(lon - LON0) * COS * K, (LAT1 - lat) * K]

function clipRing(ring, pad = 0.4) {
  const edges = [
    [(p) => p[0] >= LON0 - pad, (a, b) => cutX(a, b, LON0 - pad)],
    [(p) => p[0] <= LON1 + pad, (a, b) => cutX(a, b, LON1 + pad)],
    [(p) => p[1] >= LAT0 - pad, (a, b) => cutY(a, b, LAT0 - pad)],
    [(p) => p[1] <= LAT1 + pad, (a, b) => cutY(a, b, LAT1 + pad)],
  ]
  let out = ring
  for (const [inside, cut] of edges) {
    const input = out
    out = []
    for (let i = 0; i < input.length; i++) {
      const cur = input[i], prev = input[(i + input.length - 1) % input.length]
      if (inside(cur)) {
        if (!inside(prev)) out.push(cut(prev, cur))
        out.push(cur)
      } else if (inside(prev)) out.push(cut(prev, cur))
    }
    if (!out.length) break
  }
  return out
}
const cutX = (a, b, x) => [x, a[1] + ((b[1] - a[1]) * (x - a[0])) / (b[0] - a[0])]
const cutY = (a, b, y) => [a[0] + ((b[0] - a[0]) * (y - a[1])) / (b[1] - a[1]), y]

function simplify(pts, tol) {
  if (pts.length < 3) return pts
  const keep = new Uint8Array(pts.length)
  keep[0] = keep[pts.length - 1] = 1
  const stack = [[0, pts.length - 1]]
  while (stack.length) {
    const [a, b] = stack.pop()
    let max = 0, idx = -1
    for (let i = a + 1; i < b; i++) {
      const d = segDist(pts[i], pts[a], pts[b])
      if (d > max) (max = d), (idx = i)
    }
    if (max > tol) {
      keep[idx] = 1
      stack.push([a, idx], [idx, b])
    }
  }
  return pts.filter((_, i) => keep[i])
}
function segDist(p, a, b) {
  const dx = b[0] - a[0], dy = b[1] - a[1]
  const len = dx * dx + dy * dy
  const t = len ? Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / len)) : 0
  return Math.hypot(p[0] - a[0] - t * dx, p[1] - a[1] - t * dy)
}
const r = (n) => Math.round(n * 10) / 10
const toPath = (rings, close = true) =>
  rings
    .filter((ring) => ring.length > 2 || !close)
    .map((ring) => 'M' + ring.map((p) => `${r(p[0])} ${r(p[1])}`).join('L') + (close ? 'Z' : ''))
    .join('')
const polys = (g) => (g.type === 'Polygon' ? [g.coordinates] : g.coordinates)

// Land (coastline), clipped to the view.
const land = topojson.feature(land50, land50.objects.land)
const landGeoms = land.type === 'FeatureCollection' ? land.features.map((f) => f.geometry) : [land.geometry]
const landRings = landGeoms.flatMap((g) => polys(g).flatMap((poly) => poly.map((ring) => simplify(clipRing(ring).map(project), 1.2))))

// Today's Bulgaria.
const countries = topojson.feature(world10, world10.objects.countries).features
const bg = countries.find((f) => f.id === '100')
const bgRings = polys(bg.geometry).flatMap((poly) => poly.map((ring) => simplify(ring.map(project), 0.9)))
const outline = bgRings.reduce((a, b) => (b.length > a.length ? b : a))

// Danube: exact along today's Bulgarian–Romanian border, schematic elsewhere.
const border = topojson.mesh(world10, world10.objects.countries, (a, b) => (a.id === '100' && b.id === '642') || (a.id === '642' && b.id === '100'))
let river = border.coordinates.flatMap((line) => line.filter((p) => p[0] <= 27.27))
river.sort((a, b) => a[0] - b[0])
const WEST = [[19.85, 45.25], [20.46, 44.82], [21.3, 44.72], [21.95, 44.6], [22.3, 44.62], [22.66, 44.63], [22.72, 44.4]]
const EAST = [[27.6, 44.2], [28.03, 44.34], [27.9, 44.9], [27.97, 45.27], [28.05, 45.43], [28.8, 45.3], [29.65, 45.2]]
const danube = simplify([...WEST, ...river, ...EAST].map(project), 0.9)

const out = `// GENERATED by scripts/build-balkans.mjs — do not edit by hand.
// Coastline and today's Bulgaria: Natural Earth (public domain), via world-atlas.
// The Danube outside today's Bulgarian–Romanian border is schematic.
// Projection: equirectangular, standard parallel ${PHI}°N — see src/map/wide.ts.

export const WIDE_W = ${W}
export const WIDE_H = ${H}

/** Land of the Balkans, clipped to the view. */
export const LAND_D = '${toPath(landRings)}'

/** Today's Bulgaria. */
export const BG_TODAY_D = '${toPath(bgRings)}'

/** The Danube. */
export const DANUBE_WIDE_D = '${toPath([danube], false)}'

/** Outline of today's Bulgaria in map units, for point-in-polygon checks. */
export const BG_TODAY_OUTLINE: ReadonlyArray<readonly [number, number]> = ${JSON.stringify(outline.map((p) => [r(p[0]), r(p[1])]))}
`
const target = resolve(fileURLToPath(import.meta.url), '../../src/map/balkans.ts')
writeFileSync(target, out)
console.log(`wrote ${target}: ${out.length} bytes, W=${W} H=${H}, land rings ${landRings.filter((x) => x.length > 2).length}, Bulgaria ${outline.length} pts, Danube ${danube.length} pts`)
