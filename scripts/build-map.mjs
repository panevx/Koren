/**
 * Generates src/map/geo.ts — the outline of Bulgaria and its neighbours for the KOREN map.
 *
 * Source: Natural Earth 1:10m Admin 0 countries, v4.1.0 (public domain),
 * redistributed as TopoJSON by the `world-atlas` npm package.
 * The map is NOT AI-generated: borders come from survey data.
 *
 * Usage (the two packages are needed only to regenerate the file, not by the app):
 *   mkdir /tmp/geo && cd /tmp/geo && npm i world-atlas@2 topojson-client@3
 *   node scripts/build-map.mjs /tmp/geo
 */
import { createRequire } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const dir = process.argv[2]
if (!dir) throw new Error('usage: node scripts/build-map.mjs <folder with world-atlas and topojson-client>')
const require = createRequire(join(resolve(dir), 'package.json'))
const topojson = require('topojson-client')
const world = JSON.parse(readFileSync(require.resolve('world-atlas/countries-10m.json'), 'utf8'))

// Must match src/map/projection.ts
const LON0 = 22.0, LON1 = 29.0, LAT0 = 40.95, LAT1 = 44.5, PHI = 42.7
const COS = Math.cos((PHI * Math.PI) / 180)
const W = 1000
const K = W / ((LON1 - LON0) * COS)
const H = Math.round((LAT1 - LAT0) * K)
const project = ([lon, lat]) => [(lon - LON0) * COS * K, (LAT1 - lat) * K]

const BULGARIA = '100'
const NEIGHBOURS = ['642', '688', '807', '300', '792'] // Romania, Serbia, N. Macedonia, Greece, Turkey
const DANUBE_EAST_END = 27.27 // Silistra: east of it the Romanian border is a land border, not the river

// Sutherland–Hodgman clip of a ring to the (slightly padded) view box, in lon/lat.
function clipRing(ring) {
  const pad = 0.3
  const edges = [
    [(p) => p[0] >= LON0 - pad, (a, b) => cutX(a, b, LON0 - pad)],
    [(p) => p[0] <= LON1 + pad, (a, b) => cutX(a, b, LON1 + pad)],
    [(p) => p[1] >= LAT0 - pad, (a, b) => cutY(a, b, LAT0 - pad)],
    [(p) => p[1] <= LAT1 + pad, (a, b) => cutY(a, b, LAT1 + pad)],
  ]
  let out = ring
  for (const [inside, cut] of edges) {
    const input = out
    out = []
    for (let i = 0; i < input.length; i++) {
      const cur = input[i], prev = input[(i + input.length - 1) % input.length]
      if (inside(cur)) {
        if (!inside(prev)) out.push(cut(prev, cur))
        out.push(cur)
      } else if (inside(prev)) out.push(cut(prev, cur))
    }
    if (!out.length) break
  }
  return out
}
const cutX = (a, b, x) => [x, a[1] + ((b[1] - a[1]) * (x - a[0])) / (b[0] - a[0])]
const cutY = (a, b, y) => [a[0] + ((b[0] - a[0]) * (y - a[1])) / (b[1] - a[1]), y]

// Douglas–Peucker simplification in projected units.
function simplify(pts, tol) {
  if (pts.length < 3) return pts
  const keep = new Uint8Array(pts.length)
  keep[0] = keep[pts.length - 1] = 1
  const stack = [[0, pts.length - 1]]
  while (stack.length) {
    const [a, b] = stack.pop()
    let max = 0, idx = -1
    for (let i = a + 1; i < b; i++) {
      const d = segDist(pts[i], pts[a], pts[b])
      if (d > max) (max = d), (idx = i)
    }
    if (max > tol) {
      keep[idx] = 1
      stack.push([a, idx], [idx, b])
    }
  }
  return pts.filter((_, i) => keep[i])
}
function segDist(p, a, b) {
  const dx = b[0] - a[0], dy = b[1] - a[1]
  const len = dx * dx + dy * dy
  const t = len ? Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / len)) : 0
  return Math.hypot(p[0] - a[0] - t * dx, p[1] - a[1] - t * dy)
}

const r = (n) => Math.round(n * 10) / 10
const toPath = (rings, close = true) =>
  rings
    .filter((ring) => ring.length > 2 || !close)
    .map((ring) => 'M' + ring.map((p) => `${r(p[0])} ${r(p[1])}`).join('L') + (close ? 'Z' : ''))
    .join('')

function polygonsOf(feature) {
  const g = feature.geometry
  return g.type === 'Polygon' ? [g.coordinates] : g.coordinates
}

const countries = topojson.feature(world, world.objects.countries).features
const byId = (id) => countries.find((f) => f.id === id)

// Bulgaria: every ring, projected and lightly simplified (≈1 km).
const bgRings = polygonsOf(byId(BULGARIA)).flatMap((poly) => poly.map((ring) => simplify(ring.map(project), 0.6)))
// Neighbours: clipped to the view, simplified more (≈3 km) — context only.
const nbRings = NEIGHBOURS.flatMap((id) =>
  polygonsOf(byId(id)).flatMap((poly) => poly.map((ring) => simplify(clipRing(ring).map(project), 1.5))),
)
// Danube = Bulgaria–Romania border west of Silistra.
const border = topojson.mesh(world, world.objects.countries, (a, b) =>
  (a.id === BULGARIA && b.id === '642') || (a.id === '642' && b.id === BULGARIA),
)
const danube = border.coordinates
  .map((line) => line.filter((p) => p[0] <= DANUBE_EAST_END))
  .filter((line) => line.length > 1)
  .map((line) => simplify(line.map(project), 0.6))

const outline = bgRings.reduce((a, b) => (b.length > a.length ? b : a))

const out = `// GENERATED by scripts/build-map.mjs — do not edit by hand.
// Source: Natural Earth 1:10m Admin 0 countries v4.1.0 (public domain), via world-atlas.
// Projection: equirectangular, standard parallel ${PHI}°N — see src/map/projection.ts.

export const MAP_W = ${W}
export const MAP_H = ${H}

/** Bulgaria (all rings). */
export const BULGARIA_D = '${toPath(bgRings)}'

/** Romania, Serbia, North Macedonia, Greece, Turkey — clipped to the view. */
export const NEIGHBOURS_D = '${toPath(nbRings)}'

/** The Danube along the northern border (the Bulgaria–Romania border west of Silistra). */
export const DANUBE_D = '${toPath(danube, false)}'

/** Main outline of Bulgaria in map units, for point-in-polygon checks in tests. */
export const BULGARIA_OUTLINE: ReadonlyArray<readonly [number, number]> = ${JSON.stringify(outline.map((p) => [r(p[0]), r(p[1])]))}
`
const target = resolve(fileURLToPath(import.meta.url), '../../src/map/geo.ts')
writeFileSync(target, out)
console.log(`wrote ${target}: ${out.length} bytes, W=${W} H=${H}, Bulgaria ${bgRings.map((x) => x.length)} pts, neighbours ${nbRings.length} rings, Danube ${danube.map((x) => x.length)} pts`)
